#!/usr/bin/env python3
"""mkhdr.py - derive b1/mini.h from mini.c's substrate region.

mini.c has two build modes (B-1 standalone, B-2 substrate). A generated .c
needs the substrate's DECLARATIONS, so this extracts them mechanically rather
than by hand: a drift between mini.c and mini.h then shows up as a compile
error in the B-2 gate, which is the failure mode we want. A hand-written header
would drift silently and produce a wrong answer instead.

The substrate region is everything before the `#ifndef MX_SUBSTRATE` that guards
the AST/lexer/parser/evaluator.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "mini.c")
OUT = os.path.join(HERE, "mini.h")

PREAMBLE = """/* mini.h - the substrate's public surface for GENERATED code.
 *
 * GENERATED by mkhdr.py from mini.c's substrate region - do not edit by hand.
 * A drift between mini.c and this file shows up as a COMPILE ERROR in the B-2
 * gate, which is the failure mode we want; a hand-maintained header would
 * drift silently and produce a wrong answer instead.
 *
 * Two build modes, one source:
 *   cc mini.c                     the whole interpreter  (B-1's gate)
 *   cc -DMX_SUBSTRATE -c mini.c   the substrate alone    (B-2 links this)
 */

#ifndef MINI_H
#define MINI_H

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <setjmp.h>
#ifdef _WIN32
#ifndef WIN32_LEAN_AND_MEAN
#define WIN32_LEAN_AND_MEAN
#endif
#include <windows.h>
#endif

/* --- types, verbatim from mini.c --- */
%s

/* --- the error channel's state, EXTERNAL in substrate mode -------------
 * The emitted code calls setjmp(g_catch) itself - it must, because setjmp
 * records the CALLING frame and a helper would leave that frame dead, and the
 * longjmp would then kill the process silently. So these three are public
 * surface, not file-static internals.
 */
/* The catch-stack macro. mx_push_catch is a MACRO and not a function because
 * setjmp must appear TEXTUALLY in the frame that will receive the jump - a
 * function would record its own returning frame, and the longjmp would land in
 * a dead one. That is the B-2 mx_try_enter defect, and it is why the generated
 * code cannot be given a helper either. The EVALUATOR gets it from mini.c; the
 * generated code gets it from here, so both share one definition. */
#define MX_CATCH_MAX 32
extern jmp_buf  g_catch_stack[MX_CATCH_MAX];
extern int      g_catch_sp;
#define mx_push_catch() \
    (g_catch_sp >= MX_CATCH_MAX ? 0 \
     : (setjmp(g_catch_stack[g_catch_sp++]) == 0))

extern MxSignal g_sig;
extern int      g_has_catch;

/* --- the substrate's entry points --- */
%s

extern MxEnv *g_globals;

#endif /* MINI_H */
"""


def main():
    text = open(SRC).read()
    start = text.index("typedef enum {\n    MX_NULL")
    # The region copied into the header is [types .. the AST half]. The AST
    # half's guard is the LAST such line in the file, and taking the FIRST match
    # picked up an earlier one - which silently truncated the header from 86
    # prototypes to 32 and made every generated program fail to compile on an
    # undeclared mx_binop. rindex, not index, with a comment saying why, because
    # the failure mode is a header that is quietly missing most of itself.
    guard = text.rindex("#if !defined(MX_SUBSTRATE) || defined(MX_BOTH)")
    region = text[start:guard]

    # The type material is copied VERBATIM. An earlier version line-filtered it
    # to drop the file-static globals, and that silently deleted the BODY of
    # struct MxValue - so the generated code compiled against a struct with no
    # `tag` and no union members, sizeof 8 instead of 16, and every MxValue was
    # silently mis-laid-out. It compiled; it just crashed. Types are therefore
    # copied whole and the globals are removed from the SOURCE instead.
    first_fn = region.index("MXFN ")
    types = region[:first_fn].rstrip()
    # mx_call_fn_ptr's DEFINITION leaks into this prefix (it sits inside an
    # #ifdef the prefix spans) and the prefix would carry a half-line of its
    # signature into the header - the wrapped-signature failure once more. The
    # prototype is emitted from its own extraction below, matched to its closing
    # paren, so the definition is dropped here rather than repaired.
    # The whole DEFINITION of mx_call_fn_ptr leaks into this prefix (it sits
    # inside an #ifdef the prefix spans), so the header gets a function BODY where
    # a prototype belongs. Its prototype is emitted from the dedicated extraction
    # below; the definition is dropped HERE rather than repaired, because the
    # header must not carry linkage the substrate's MXFN macro decides.
    # (no filtering needed: mx_call_fn_ptr lives past the region now)

    # The arena's chunk struct is an implementation detail, not public surface.
    types = re.sub(r"typedef struct ArenaChunk \{.*?\} ArenaChunk;\n\n", "", types,
                   flags=re.S)
    # The env chain and the signal struct live further down the region (they
    # were moved there for B-2), so pull them up front. Written out here
    # explicitly rather than scraped, because scraping a struct definition is
    # exactly the kind of thing that silently drops a member.
    import re as _re
    def _grab(start, endpat):
        m = _re.search(start + r".*?" + endpat, text, _re.S)
        return m.group(0) if m else ""
    _binding = _grab(r"typedef struct Binding \{", r"\} Binding;")
    _env      = _grab(r"typedef struct MxEnv \{", r"\} MxEnv;")
    _kind     = _grab(r"typedef enum \{\s*\n?\s*K_NONE", r"\} MxKind;")
    _sig      = _grab(r"typedef struct \{\s*\n?\s*int\s+kind;", r"\} MxSignal;")
    # MxFnGen is the generated-code calling convention, declared AFTER the first
    # MXFN and therefore outside the `types` prefix. It is extracted here for the
    # same reason as the rest: a hand-written prototype in the header is a second
    # copy of a signature, and a mismatch is a COMPILE error only in the
    # generated path - exactly where the interpreted gate cannot see it.
    _fngen    = _re.search(r"typedef MxValue \(\*MxFnGen\)\([^;]*?\);", text, _re.S).group(0)
    # The generated path's boxes and class descriptor. Generated code NAMES
    # MxClassDesc (it declares a static one per class), so the header must
    # define it - the same rule as MxFnGen and the same reason: a hand-written
    # copy in the header is a second description that drifts.
    # Spelled out, not grepped: a greedy match for the struct also matched the
    # DISPLAY helpers' bodies (which name the same types), and the header then
    # carried function definitions referencing interpreter-only types.
    _cdesc = ("struct MxClassDesc_ {\n"
              "    const char      *name;\n"
              "    const char      *parent;\n"
              "    const char     **field_names;\n"
              "    MxValue         *field_vals;\n"
              "    int              nfields;\n"
              "    const char     **method_names;\n"
              "    MxFnGen         *method_fns;\n"
              "    int              nmethods;\n"
              "    MxFnGen          init_fn;\n"
              "    int              init_arity;\n"
              "    MxEnv           *mod_env;\n"
              "    void            *defined;\n"
              "};")
    _cdesc_td = "typedef struct MxClassDesc_ MxClassDesc;"
    _geninst  = "typedef struct { int64_t stamp; MxClassDesc *klass; MxDict *fields; } MxGenInst;"
    _genbound = ("struct MxGenBound_ { int64_t stamp; MxFnGen fn; "
                 "MxGenInst *inst; MxClassDesc *klass; };")
    _gensuper = "struct MxGenSuper_ { MxGenInst *inst; MxClassDesc *klass; };"
    # The generated path's FOUR entry points, spelled out for the same reason:
    # they are declared inside an #ifdef, and the main prototype loop only walks
    # the SUBSTRATE region, so generated code would call them undeclared.
    _genapi = "\n".join([
        "void mx_register_class(MxClassDesc *d);",
        "MxValue mx_dot(MxValue obj, const char *field);",
        "MxValue mx_new(const char *class_name, MxValue a0, int nargs);",
        "MxValue mx_new_multi(const char *class_name, MxValue *args, int nargs);",
        "void mx_set_field(MxValue obj, const char *field, MxValue val);",
        "MxValue mx_import_module(const char *name);",
        "void mx_set_argv0(const char *argv0);",
        "void mx_set_source(const char *src_path);",
        "void mx_set_argv_full(char **argv, int argc);",
        "void mx_install_safety_nets(void);",
        "MxValue mx_file_builtin(const char *kind, MxValue *args, int nargs);",
        "MxValue mx_input(MxValue prompt);",
        "MxValue mx_call_list(const char *name, MxValue recv, MxValue p0, MxValue p1, MxValue p2, MxValue p3, MxValue p4, MxValue p5, int nargs);",
    ])
    _genboxes = "\n".join([_cdesc, _cdesc_td, _geninst, _genbound,
                           "typedef struct MxGenBound_ MxGenBound;", _gensuper,
                           "typedef struct MxGenSuper_ MxGenSuper;"])
    # The mx_call_fn_ptr PROTOTYPE is wrapped across two lines in mini.c, and the
    # extractor takes one line - the same "assume one line" mistake that produced
    # a header prototype ending in a comma. It is matched to its closing paren
    # here, and the newlines are collapsed, because the header must be valid C
    # whatever shape the source uses.
    _mfp = _re.search(r"MXFN MxValue mx_call_fn_ptr\(.*?\) \{", text, _re.S)
    _mfp_txt = " ".join(_mfp.group(0)[:-2].split()) if _mfp else ""
    _maxpar   = _re.search(r"#define MX_MAX_PARAMS \d+", text).group(0)
    _missing  = [nm for nm, txt in (("Binding", _binding), ("MxEnv", _env),
                                    ("MxKind", _kind), ("MxSignal", _sig),
                                    ("MxFnGen", _fngen), ("MX_MAX_PARAMS", _maxpar),
                                    ("mx_call_fn_ptr", _mfp_txt)) if not txt]
    if _missing:
        raise SystemExit("mkhdr: could not extract %s from mini.c - the "
                         "substrate region moved" % ", ".join(_missing))
    # Extracted, never retyped. The four blocks below were HAND-COPIED into this
    # generator once, and that copy is what let mini.h keep a four-kind enum
    # after mini.c grew to six - every generated `break` failed to COMPILE with
    # "'K_CONTINUE' undeclared", while the interpreted path was perfectly green.
    # A duplicated type block drifts silently and always in the direction that
    # only the generated path notices.
    env_types = "\n".join(t for t in (_binding, _env, _kind, _sig,
                                      _maxpar, _fngen, _genboxes) if t)
    env_types = env_types.replace("MXFN ", "")

    types = types + "\n" + env_types

    # File-static state the emitted code never names: g_arena, g_sig, g_catch,
    # g_has_catch. Dropped STRUCTURALLY (a line ending in ';' that declares a
    # global, i.e. one with no '(' in it) rather than by pattern, because a
    # pattern missed one of them and the header failed to compile.
    # The file-static globals (g_arena, g_sig, g_catch, g_has_catch) live above
    # the types; strip those LINES only, never a struct body.
    # Drop the file-static INTERNALS: g_arena, and g_stamp. Keep g_sig, g_catch
    # and g_has_catch, which must be extern because the emitted code calls
    # setjmp itself. A file-static definition in a HEADER is a separate
    # variable in every translation unit - the exact defect that made
    # mx_try_enter's flag invisible - so these must never be copied across. An earlier version filtered "any line ending in ; with no
    # (", which also deleted struct MEMBERS like `MxTag tag;` - so mini.h
    # declared a struct MxValue with no tag and no union, sizeof 8 not 16, and
    # every generated MxValue was silently mis-laid-out. It COMPILED. It just
    # crashed. Match the four names explicitly, never a shape.
    _drop = ("g_arena", "static int64_t g_stamp", "g_stamp = 0;")
    types = "\n".join(l for l in types.split("\n")
                     if not any(l.strip().startswith(d) for d in _drop))

    protos = []
    lines = region[first_fn:].split("\n")
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("MXFN "):
            head = line[len("MXFN "):]
            # mx_call_fn_ptr is emitted from its own extraction below (it is
            # matched to its closing paren, not to the end of the line). Taking
            # it here as well produced a prototype cut at the line break - the
            # wrapped-signature defect a third time, in the same file.
            if head.startswith("MxValue mx_call_fn_ptr("):
                i += 1
                continue
            # single-line body: `MXFN T f(args) { ... }` on one line
            if head.rstrip().endswith("}") and "{" in head:
                protos.append(head.rstrip()[:head.rstrip().index("{")].rstrip() + ";")
                i += 1
                continue
            if head.rstrip().endswith("{"):
                depth = 0
                j = i
                while True:
                    depth += lines[j].count("{") - lines[j].count("}")
                    if depth == 0 and j > i:
                        break
                    j += 1
                protos.append(head.rstrip()[:-1].rstrip() + ";")
                i = j + 1
                continue
            # A signature that WRAPS. This branch used to take the first line
            # only, so a two-line declaration such as
            #     MXFN void mx_display_into(MxValue v, char *out, size_t n, int quote,
            #                                int64_t *seen, int depth) {
            # produced a header prototype ending in a comma. That is not a
            # warning - it is a PARSE ERROR, and the next declaration in the
            # header got absorbed as a parameter list, so every generated
            # program failed with "storage class specified for parameter
            # 'g_globals'" pointing at a line twenty declarations later.
            #
            # The lesson is the same shape as the type-block filter: an
            # extractor that assumes one thing per line will meet one that is
            # not. Join until the parameter list is CLOSED, which is what a C
            # reader does, rather than assuming a single line.
            sig = head.rstrip()
            if not sig.endswith(";"):
                j = i
                while j + 1 < len(lines) and "(" in sig and sig.count("(") > sig.count(")"):
                    j += 1
                    sig = sig.rstrip() + " " + lines[j].strip()
                protos.append(sig.rstrip().rstrip("{").rstrip() + ";")
                i = j + 1
                continue
            protos.append(head)
            i += 1
            continue
        i += 1

    # mx_call_fn_ptr is appended here rather than by the loop above: it lives past
    # the substrate region (it is emit-facing, not evaluator-facing) and its
    # signature is matched to its closing paren, not to a line break.
    if _mfp_txt:
        protos.append(_mfp_txt.replace("MXFN ", "") + ";")
    # The generated path's four entry points, which live inside an #ifdef the
    # main loop never walks.
    protos = protos + [l for l in _genapi.split("\n") if l]

    open(OUT, "w").write(PREAMBLE % (types, "\n".join(protos)))
    print("wrote %s: %d prototypes" % (os.path.basename(OUT), len(protos)))
    return 0


if __name__ == "__main__":
    sys.exit(main())